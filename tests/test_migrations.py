def test_store_adopts_a_database_built_before_migrations_existed(tmp_path) -> None:
    """A `piano.db` from the create_all days has the schema but no version table.

    It is stamped with the initial revision and upgraded from there, instead of
    failing on tables that already exist or being reseeded from scratch.
    """
    url = f"sqlite+pysqlite:///{tmp_path / 'legacy.db'}"
    legacy_engine = create_database_engine(url)
    Base.metadata.create_all(legacy_engine)
    with create_session_factory(legacy_engine).begin() as session:
        session.add(
            TeacherSettingsRecord(
                id=1, username="admin", password_hash="not-a-real-hash", timezone="Europe/Oslo"
            )
        )
        session.add(
            StudentRecord(
                id=1,
                name="Legacy Student",
                status="active",
                token="legacy",
                slot_day=2,
                slot_time="16:15",
            )
        )
        session.flush()
        session.add(PackageRecord(student_id=1, size=10, used=3, period_no=1, invoice_sent=False))
    legacy_engine.dispose()

    store = DatabaseStore(url)
    with store.engine.connect() as connection:
        revision = current_revision(connection)

    assert revision == head_revision()
    assert store.student_for_token("legacy").name == "Legacy Student"
    assert list(store.students) == [1]
    store.engine.dispose()


def test_migrate_target_upgrades_the_configured_database(tmp_path) -> None:
    """`make migrate` reads PIANO_DATABASE_URL exactly as the application does."""
    database = tmp_path / "cli.db"
    result = subprocess.run(
        ["make", "migrate"],
        cwd=REPO_ROOT,
        capture_output=True,
        text=True,
        env={**os.environ, "PIANO_DATABASE_URL": f"sqlite+pysqlite:///{database}"},
    )
    engine = create_database_engine(f"sqlite+pysqlite:///{database}")
    with engine.connect() as connection:
        revision = current_revision(connection)

    assert result.returncode == 0, result.stderr
    assert database.exists()
    assert revision == head_revision()
    assert _table_names(engine) == {table.name for table in Base.metadata.sorted_tables}
    engine.dispose()
